create sequence savis_api.order_number_sequence start with 1 increment by 1;

create table savis_api.orders (
    id bigint generated by default as identity primary key,
    public_id uuid not null unique,
    order_number varchar(255) not null unique,
    source varchar(255) not null,
    status varchar(255) not null,
    customer_name varchar(255) not null,
    customer_phone varchar(255) not null,
    customer_email varchar(255),
    note text,
    total_cents integer not null check (total_cents >= 0),
    external_order_id uuid,
    placed_at timestamp with time zone not null,
    imported_at timestamp with time zone not null,
    accepted_at timestamp with time zone,
    in_preparation_at timestamp with time zone,
    ready_at timestamp with time zone,
    completed_at timestamp with time zone,
    cancelled_at timestamp with time zone,
    raw_payload jsonb not null,
    constraint uk_orders_source_external unique (source, external_order_id)
);

create table savis_api.order_items (
    id bigint generated by default as identity primary key,
    order_id bigint not null references savis_api.orders(id) on delete cascade,
    public_id uuid not null unique,
    product_id uuid not null,
    product_name_snapshot varchar(255) not null,
    product_type varchar(255) not null,
    image_url text,
    quantity integer not null check (quantity > 0),
    base_price_cents integer not null check (base_price_cents >= 0),
    unit_price_cents integer not null check (unit_price_cents >= 0),
    line_total_cents integer not null check (line_total_cents >= 0),
    purchase_mode_id varchar(255),
    purchase_mode_label varchar(255),
    purchase_mode_quantity integer,
    allocation_type varchar(255) not null,
    raw_key text
);

create table savis_api.order_item_choice_selections (
    id bigint generated by default as identity primary key,
    order_item_id bigint not null references savis_api.order_items(id) on delete cascade,
    choice_id varchar(255) not null,
    choice_name varchar(255) not null,
    group_label varchar(255) not null
);

create table savis_api.order_item_choice_allocations (
    id bigint generated by default as identity primary key,
    order_item_id bigint not null references savis_api.order_items(id) on delete cascade,
    choice_id varchar(255) not null,
    choice_name varchar(255) not null,
    quantity integer not null check (quantity > 0)
);

create table savis_api.order_item_ingredient_selections (
    id bigint generated by default as identity primary key,
    order_item_id bigint not null references savis_api.order_items(id) on delete cascade,
    ingredient_id varchar(255) not null,
    ingredient_name varchar(255) not null,
    quantity integer not null check (quantity >= 0),
    default_quantity integer not null check (default_quantity >= 0),
    extra_price_cents integer not null check (extra_price_cents >= 0)
);

create index idx_orders_placed_at on savis_api.orders(placed_at desc);
create index idx_orders_status_placed_at on savis_api.orders(status, placed_at desc);
create index idx_order_items_order on savis_api.order_items(order_id);
create index idx_order_choice_selections_item on savis_api.order_item_choice_selections(order_item_id);
create index idx_order_choice_allocations_item on savis_api.order_item_choice_allocations(order_item_id);
create index idx_order_ingredients_item on savis_api.order_item_ingredient_selections(order_item_id);
