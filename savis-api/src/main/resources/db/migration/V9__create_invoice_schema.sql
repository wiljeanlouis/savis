create sequence savis_api.invoice_number_sequence start with 1 increment by 1;

create table savis_api.invoices (
    id bigint generated by default as identity primary key,
    version bigint not null default 0,
    public_id uuid not null unique,
    invoice_number varchar(255) unique,
    source_order_id uuid not null unique references savis_api.orders(public_id),
    source_order_number varchar(255) not null,
    status varchar(255) not null check (status in ('DRAFT', 'ISSUED', 'CANCELLED')),
    customer_name varchar(255) not null,
    customer_phone varchar(255) not null,
    customer_email varchar(255),
    customer_address_line1 varchar(255),
    customer_address_line2 varchar(255),
    customer_city varchar(255),
    customer_province varchar(255),
    customer_postal_code varchar(32),
    note text,
    subtotal_cents integer not null check (subtotal_cents >= 0),
    discount_cents integer not null check (discount_cents >= 0 and discount_cents <= subtotal_cents),
    delivery_fee_cents integer not null check (delivery_fee_cents >= 0),
    gst_cents integer not null check (gst_cents >= 0),
    qst_cents integer not null check (qst_cents >= 0),
    total_cents integer not null check (
        total_cents >= 0
        and total_cents = subtotal_cents - discount_cents + delivery_fee_cents + gst_cents + qst_cents
    ),
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    issued_at timestamp with time zone,
    cancelled_at timestamp with time zone,
    items jsonb not null check (jsonb_typeof(items) = 'array' and jsonb_array_length(items) > 0),
    constraint ck_invoices_lifecycle check (
        (status = 'DRAFT' and invoice_number is null and issued_at is null and cancelled_at is null)
        or (status = 'ISSUED' and invoice_number is not null and issued_at is not null and cancelled_at is null)
        or (status = 'CANCELLED' and cancelled_at is not null
            and ((invoice_number is null and issued_at is null)
                or (invoice_number is not null and issued_at is not null)))
    )
);

create index idx_invoices_created_at on savis_api.invoices(created_at desc);
create index idx_invoices_status_created_at on savis_api.invoices(status, created_at desc);
