-- Independent material reference data. Names deliberately are not unique: identity is the UUID.
create table savis_api.resources (
    id bigint generated by default as identity primary key,
    public_id uuid not null unique,
    name varchar(160) not null check (trim(name) <> ''),
    description text check (description is null or char_length(description) <= 4000),
    category varchar(32) not null check (category in ('INGREDIENT', 'CONSUMABLE', 'PACKAGING', 'EQUIPMENT', 'DECORATION_MATERIAL')),
    reference_unit varchar(32) check (reference_unit in ('GRAM', 'KILOGRAM', 'LITER', 'MILLILITER', 'PIECE')),
    status varchar(16) not null check (status in ('ACTIVE', 'INACTIVE')),
    constraint ck_resources_reference_unit check (
        reference_unit is not null or category in ('EQUIPMENT', 'DECORATION_MATERIAL')
    )
);
create index idx_resources_name_public_id on savis_api.resources(name, public_id);
create index idx_resources_category_status on savis_api.resources(category, status);
