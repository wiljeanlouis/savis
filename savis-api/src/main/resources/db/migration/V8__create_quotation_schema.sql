create sequence savis_api.quotation_number_sequence start with 1 increment by 1;

create table savis_api.quotations (
    id bigint generated by default as identity primary key,
    version bigint not null default 0,
    public_id uuid not null unique,
    quotation_number varchar(255) not null unique,
    status varchar(255) not null check (status in ('DRAFT', 'SENT', 'ACCEPTED', 'REJECTED')),
    customer_name varchar(255) not null,
    customer_phone varchar(255) not null,
    customer_email varchar(255),
    customer_address_line1 varchar(255),
    customer_address_line2 varchar(255),
    customer_city varchar(255),
    customer_province varchar(255),
    customer_postal_code varchar(255),
    valid_until date not null,
    note text,
    discount_cents integer not null check (discount_cents >= 0),
    delivery_fee_cents integer not null check (delivery_fee_cents >= 0),
    total_cents integer not null check (total_cents >= 0),
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    sent_at timestamp with time zone,
    accepted_at timestamp with time zone,
    rejected_at timestamp with time zone,
    converted_order_id uuid unique references savis_api.orders(public_id),
    items jsonb not null check (jsonb_typeof(items) = 'array')
);

create index idx_quotations_created_at on savis_api.quotations(created_at desc);
create index idx_quotations_status on savis_api.quotations(status, created_at desc);
